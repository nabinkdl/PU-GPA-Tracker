// ─── getGradeFromCGPA ─────────────────────────────────────────────────────────
//
// FIX: Clamp negative / out-of-range inputs before the comparisons so no
//      caller can accidentally get an unexpected result.
//
export function getGradeFromCGPA(cgpa: number): string {
  // Guard: anything non-finite or negative is treated as 0
  const safe = isFinite(cgpa) ? Math.max(0, cgpa) : 0;

  if (safe < 1.0) return 'F';
  if (safe >= 4.0) return 'A';   // includes values slightly above 4.0
  if (safe >= 3.7) return 'A-';
  if (safe >= 3.3) return 'B+';
  if (safe >= 3.0) return 'B';
  if (safe >= 2.7) return 'B-';
  if (safe >= 2.3) return 'C+';
  if (safe >= 2.0) return 'C';
  if (safe >= 1.7) return 'C-';
  if (safe >= 1.3) return 'D+';
  return 'D';                    // 1.0 – 1.29
}

// ─── getPercentageFromCGPA ────────────────────────────────────────────────────
//
// FIX 1: Return `null` for CGPA below 2.00 instead of the misleading `0`.
//         Callers can decide how to display "not applicable".
//
// FIX 2: Use integer-based rounding ( round(cgpa * 100) ) on the raw value
//         *before* any arithmetic, which sidesteps most IEEE-754 drift that
//         the previous boundedCGPA path could introduce.
//
export function getPercentageFromCGPA(cgpa: number): number | null {
  if (!isFinite(cgpa) || cgpa < 2.00) return null;

  // Clamp to [2.00, 4.00]
  const bounded = Math.min(4.00, cgpa);

  // FIX: Multiply first, round as integer, then divide — avoids floating-point
  //      representation issues like 3.145 * 100 → 314.49999…
  const key = (Math.round(bounded * 100) / 100).toFixed(2);

  const percentage = cgpaToPercentage[key];

  // The lookup table covers every 0.01 step in [2.00, 4.00], so this branch
  // should only ever be reached if bounded somehow falls outside the table.
  if (percentage !== undefined) {
    return percentage;
  }

  // Safe linear interpolation fallback (shouldn't normally be reached)
  return 60.00 + ((bounded - 2.00) / 2.00) * 30.00;
}
